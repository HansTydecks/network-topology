    function t(key) {
        return (translations[currentLang] && translations[currentLang][key]) || translations.de[key] || key;
    }

    function setLang(lang) {
        if (translations[lang]) {
            currentLang = lang;
            localStorage.setItem('topo-lang', lang);
        }
    }

    function getLang() { return currentLang; }

    function loadLang() {
        const saved = localStorage.getItem('topo-lang');
        if (saved && translations[saved]) currentLang = saved;
    }

    function getAvailableLanguages() {
        return Object.keys(translations);
    }

    return { t, setLang, getLang, loadLang, getAvailableLanguages };
